/**
 * `bun run test:load` — closed-loop load test against 3 real instances (spawned here) sharing
 * PostgreSQL + LocalStack. Reports throughput, p50/p95/p99, error rate, status mix, lock
 * conflicts (from /metrics) and outbox lag. Writes test/load/RESULTS.md.
 *
 * Knobs: LOAD_REQUESTS (default 3000), LOAD_CONCURRENCY (64), LOAD_WALLETS (50), LOAD_HOT_RATIO (0.3)
 */
import { cpus, totalmem } from 'node:os';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  closeOrm, createQueues, createWallet, deleteQueues, http, instanceEnv, resetDatabase, spawnInstance, sql, stopInstance, submit, wager,
} from '../support/env';

const REQUESTS = Number(process.env.LOAD_REQUESTS ?? 3000);
const CONCURRENCY = Number(process.env.LOAD_CONCURRENCY ?? 64);
const WALLETS = Number(process.env.LOAD_WALLETS ?? 50);
const HOT_RATIO = Number(process.env.LOAD_HOT_RATIO ?? 0.3);
const DUP_RATIO = 0.05;

function percentile(sorted: number[], p: number) {
  if (!sorted.length) return 0;
  return sorted[Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1)]!;
}

async function scrape(url: string, metric: string): Promise<number> {
  const text = await (await fetch(`${url}/metrics`)).text();
  return text
    .split('\n')
    .filter((l) => l.startsWith(metric))
    .reduce((acc, l) => acc + Number(l.split(' ').at(-1)), 0);
}

async function main() {
  await resetDatabase();
  const q = await createQueues('load');
  const env = instanceEnv(q, { CONSUMER_ENABLED: 'false', DB_POOL_MAX: '20' });
  const instances = await Promise.all([3301, 3302, 3303].map((p, i) => spawnInstance(`load-${i + 1}`, p, env)));
  const urls = instances.map((i) => i.url);
  try {
    const wallets = await Promise.all(Array.from({ length: WALLETS }, (_, i) => createWallet(urls[i % 3]!, '1000000.00')));
    const hot = wallets[0]!;
    const latencies: number[] = [];
    const statuses = new Map<number, number>();
    let errors = 0;
    let issued = 0;
    let lagMax = 0;
    const lagSampler = setInterval(async () => {
      const r = await sql(`select coalesce(extract(epoch from now() - min(occurred_at)), 0)::float8 as lag from outbox_messages where published_at is null`).catch(() => [{ lag: 0 }]);
      lagMax = Math.max(lagMax, Number(r[0]!.lag));
    }, 250);

    const started = performance.now();
    const worker = async (wid: number) => {
      while (true) {
        const i = issued++;
        if (i >= REQUESTS) return;
        const isDup = i > 10 && Math.random() < DUP_RATIO;
        const n = isDup ? Math.floor(Math.random() * (i - 1)) : i;
        // Deterministic per n, so a replay of key n carries exactly the same payload.
        const w = (n * 7919) % 100 < HOT_RATIO * 100 ? hot : wallets[1 + (n % (WALLETS - 1))]!;
        const kind = n % 4 === 0 ? 'WIN' : 'BET';
        const t0 = performance.now();
        try {
          const res = await submit(urls[(i + wid) % 3]!, wager(w, `load-${n}`, kind, '1.00'));
          statuses.set(res.status, (statuses.get(res.status) ?? 0) + 1);
          if (res.status >= 500) errors++;
        } catch {
          errors++;
        }
        latencies.push(performance.now() - t0);
      }
    };
    await Promise.all(Array.from({ length: CONCURRENCY }, (_, i) => worker(i)));
    const elapsedSec = (performance.now() - started) / 1000;

    // Drain: how long until the outbox is fully published after the load stops.
    const drainStart = performance.now();
    while ((await sql(`select count(*)::int as n from outbox_messages where published_at is null`))[0]!.n > 0) await Bun.sleep(100);
    const drainSec = (performance.now() - drainStart) / 1000;
    clearInterval(lagSampler);

    const lockConflicts = (await Promise.all(urls.map((u) => scrape(u, 'wagering_lock_conflicts_total')))).reduce((a, b) => a + b, 0);
    const retries = (await Promise.all(urls.map((u) => scrape(u, 'wagering_retries_total')))).reduce((a, b) => a + b, 0);
    const replays = (await Promise.all(urls.map((u) => scrape(u, 'wagering_duplicates_detected_total')))).reduce((a, b) => a + b, 0);
    let consistent = true;
    for (const w of wallets) consistent &&= (await http(urls[0]!, 'POST', `/wallets/${w.walletId}/reconciliation`)).body.consistent;

    latencies.sort((a, b) => a - b);
    const report = `# Load test results

_Generated by \`bun run test:load\` on ${new Date().toISOString()}_

## Environment
- Host: ${cpus().length} vCPU (${cpus()[0]?.model ?? 'unknown'}), ${(totalmem() / 2 ** 30).toFixed(1)} GiB RAM, ${process.platform}
- 3 service instances (Bun ${Bun.version}) as separate OS processes on the host, pool 20 connections each
- PostgreSQL 16 + LocalStack SQS in Docker Desktop (WSL2), same machine — **client, app and DB compete for the same CPUs**

## Methodology
- Closed loop: ${CONCURRENCY} concurrent virtual clients, ${REQUESTS} \`POST /wagering/transactions\` requests, round-robin over 3 instances
- ${WALLETS} wallets; ${(HOT_RATIO * 100).toFixed(0)}% of requests hit a single **hot wallet** (worst case for row-lock contention)
- 75% BET / 25% WIN of 1.00 BRL; ~${(DUP_RATIO * 100).toFixed(0)}% of requests are replays of an earlier key (idempotency path)
- Outbox lag sampled every 250 ms during the run; drain time measured after the last response

## Results
| metric | value |
|---|---|
| throughput | **${(REQUESTS / elapsedSec).toFixed(0)} req/s** (${elapsedSec.toFixed(1)} s total) |
| latency p50 / p95 / p99 | ${percentile(latencies, 50).toFixed(1)} / ${percentile(latencies, 95).toFixed(1)} / ${percentile(latencies, 99).toFixed(1)} ms |
| latency max | ${latencies.at(-1)?.toFixed(1)} ms |
| error rate (5xx / network) | ${((errors / REQUESTS) * 100).toFixed(2)}% (${errors}) |
| HTTP status mix | ${[...statuses].sort().map(([s, c]) => `${s}: ${c}`).join(', ')} |
| lock conflicts (metric) | ${lockConflicts} |
| retries (metric) | ${retries} |
| duplicates detected | ${replays} |
| outbox lag (max during run) | ${lagMax.toFixed(2)} s |
| outbox drain after load | ${drainSec.toFixed(2)} s |
| reconciliation of all wallets | ${consistent ? 'consistent ✅' : 'DIVERGENT ❌'} |

## Reading the numbers
- Every write to a wallet serializes on its row lock, so the hot wallet caps at roughly 1 / (lock hold time):
  the p99 is dominated by requests queued behind it. Cold wallets scale with instances and pool size.
- \`lock conflicts\` counts optimistic version mismatches and SKIP LOCKED skips; with pessimistic locking
  contention shows up as **queueing latency**, not as errors.
- Everything runs on one laptop, so absolute numbers are a lower bound; the relative behaviour
  (hot wallet vs cold wallets, zero errors, consistent ledger) is what this experiment shows.
`;
    writeFileSync(resolve(import.meta.dir, 'RESULTS.md'), report);
    console.log(report);
  } finally {
    await Promise.all(instances.map((i) => stopInstance(i)));
    await deleteQueues(q);
    await closeOrm();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
